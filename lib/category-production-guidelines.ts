function familyForProfile(profileId: string): ProductionGuidelineFamily {
  if (profileId.startsWith("food-")) return "food";
  if (profileId.startsWith("health-")) return "health-supplement";
  if (profileId.startsWith("beauty-")) return "cosmetics";
  if (/^fashion-(?:tops|knit|bottoms|dress|outer|activewear|underwear|sleepwear|kids|socks)$/.test(profileId)) return "apparel";
  if (profileId.startsWith("fashion-")) return "fashion-accessory";
  if (profileId.startsWith("kitchen-") || profileId === "home-cookware" || profileId === "home-tableware") return "kitchen";
  if (profileId.startsWith("home-")) return "home-living";
  if (profileId.startsWith("digital-")) return "digital-electronics";
  if (profileId.startsWith("pet-")) return "pet";
  if (profileId === "baby-care") return "baby";
  if (profileId.startsWith("toy-")) return "toys-hobby";
  if (profileId.startsWith("office-")) return "office";
  if (profileId === "sport-fitness" || profileId === "outdoor-camping") return "sports-outdoor";
  if (profileId === "tools-diy" || profileId === "auto-accessory" || profileId === "garden-plant") return "tools-auto-garden";
  return "general";
}

const generalSubtype: SubtypeDirection = {
  subject: "실제 상품의 전체 형태와 정면 식별",
  useState: "확인된 용도에 맞는 사용 전 준비 상태",
  detailFocus: "구조·재질·결합부·실제 구성",
  evidenceFocus: "치수·재질·사용법·주의사항",
  forbidden: "미확인 기능·성능·구성·사용 결과",
};

export function resolveCategoryProductionGuideline(profileId: string): CategoryProductionGuideline {
  const family = familyForProfile(profileId);
  const familyPolicy = familyPolicies[family];
  const subtype = subtypeDirections[profileId] ?? generalSubtype;
  const slotDirectives: Record<ProductionGuidelineSlot, string> = {
    portrait: `${subtype.subject}; 정면 식별과 전체 실루엣을 가장 먼저 보여주는 대표컷`,
    wide: `${subtype.subject}; 실제 수량과 구성 관계를 읽을 수 있는 가로 구성컷`,
    "detail-overview": `${subtype.subject}; 앞·옆·위 구조가 겹치지 않게 보이는 전체 확인컷`,
    "detail-use": `${subtype.useState}; 상품이 장면의 중심에서 실제 사용 단계를 설명하는 컷`,
    "detail-routine": `${subtype.useState}; 사용 전 준비와 다음 행동이 혼동되지 않는 순서컷`,
    "detail-scale": `${subtype.detailFocus}; 왜곡을 줄이고 크기·비율·결합 구조를 판단하는 컷`,
    "detail-storage": `${subtype.detailFocus}; 밀봉·접힘·뚜껑·잠금·보관 상태 중 해당 구조를 확인하는 컷`,
    "detail-context": `${subtype.evidenceFocus}; 표시사항 사진을 광고 배경으로 바꾸지 않고 구매 판단 항목과 연결하는 마무리컷`,
  };
  return {
    version: CATEGORY_PRODUCTION_GUIDELINE_VERSION,
    family,
    profileId,
    ...familyPolicy,
    ...subtype,
    slotDirectives,
  };
}

